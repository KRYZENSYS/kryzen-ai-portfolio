window.applyI18n = (lang) => {
  if (!window.I18N[lang]) lang = 'uz';
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (I18N[lang][key] !== undefined) {
      // Preserve icons in nav items by allowing mixed content
      el.textContent = I18N[lang][key];
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (I18N[lang][key]) el.placeholder = I18N[lang][key];
  });
  // Update active lang button
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === lang);
  });
  localStorage.setItem('kryzen_lang', lang);
  window.currentLang = lang;
};

// Init on load
window.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('kryzen_lang') || 'uz';
  applyI18n(saved);

  document.querySelectorAll('.lang-btn').forEach(b => {
    b.addEventListener('click', () => applyI18n(b.dataset.lang));
  });
});
